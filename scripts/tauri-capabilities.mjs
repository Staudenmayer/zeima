#!/usr/bin/env node
// Which window may call which of the app's commands (docs/security.md, ZE-14). A compromised page in a small window
// (quick switch, prompt) must not be able to install addons or call the organization API, so those windows get only
// the commands their code can reach; the main window gets all of them.
//
//   node scripts/tauri-capabilities.mjs          write src-tauri/capabilities/{main,bare}.json
//   node scripts/tauri-capabilities.mjs --check  fail if they are out of date (also run by `bun run test`)
//
// The small windows' commands are found by reading the code: every `commands.<name>(...)` in the files that window's
// pages import, transitively (stores, composables, components). Over-including is safe, under-including breaks the
// window, so the whole import closure counts, not just what happens to run. The commands themselves are those in
// `collect_commands![…]` of src-tauri/src/lib.rs (src-tauri/build.rs reads the same list).

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'src')

/** The command names of `collect_commands![…]`, as in lib.rs. */
export function appCommands(libRs = readFileSync(join(root, 'src-tauri/src/lib.rs'), 'utf8')) {
  const block = /collect_commands!\[([\s\S]*?)\]\)/.exec(libRs)?.[1]
  if (!block) throw new Error('collect_commands! not found in src-tauri/src/lib.rs')
  return [...block.matchAll(/(?:\w+::)+(\w+)\s*,?/g)].map((m) => m[1])
}

/** camelCase (bindings.ts) → the command's name as the backend knows it. */
export function bindingNames(bindings = readFileSync(join(src, 'bindings.ts'), 'utf8')) {
  const map = new Map()
  for (const m of bindings.matchAll(/^\t(\w+): [\s\S]*?__TAURI_INVOKE[^(\n]*\("(\w+)"/gm)) map.set(m[1], m[2])
  return map
}

const EXTENSIONS = ['', '.ts', '.vue', '.js', '/index.ts', '/index.vue', '/index.js']

function resolveImport(from, spec) {
  let base
  if (spec.startsWith('@/')) base = join(src, spec.slice(2))
  else if (spec.startsWith('./') || spec.startsWith('../')) base = resolve(dirname(from), spec)
  else return null // a package
  for (const ext of EXTENSIONS) {
    const file = base + ext
    if (existsSync(file) && /\.(ts|vue|js)$/.test(file)) return file
  }
  return null
}

/** The commands the files reach by importing, starting from `entries`. */
export function reachableCommands(entries, names = bindingNames()) {
  const seen = new Set()
  const found = new Set()
  const queue = entries.map((e) => join(src, e))
  while (queue.length) {
    const file = queue.pop()
    if (seen.has(file)) continue
    seen.add(file)
    const text = readFileSync(file, 'utf8')
    for (const m of text.matchAll(/\bcommands\.(\w+)/g)) {
      const name = names.get(m[1])
      if (!name) throw new Error(`${file}: commands.${m[1]} is not in bindings.ts`)
      found.add(name)
    }
    for (const m of text.matchAll(/(?:from|import)\s*\(?\s*['"]([^'"]+)['"]/g)) {
      const next = resolveImport(file, m[1])
      if (next) queue.push(next)
    }
  }
  return found
}

/** What the quick switch and prompt windows load: the shared start-up code, the bare layout and their two pages. */
export const BARE_ENTRIES = ['plugins/backend.ts', 'plugins/router.ts', 'plugins/i18n.ts', 'layouts/bare.vue', 'pages/quickswitch.vue', 'pages/prompt.vue']

/**
 * Commands the shared stores contain (so the import closure reaches them) but that the quick switch and prompt code
 * never calls: deleting catalog entries, saving cost centers and writing settings. Checked against their entry code;
 * a compromised small window must not get them (least privilege). Add a command here only after checking that no
 * code the bare windows run calls it.
 */
export const BARE_DENIED = ['activity_delete', 'project_delete', 'tag_delete', 'cost_center_delete', 'cost_center_save', 'settings_set']

const permissionOf = (command) => `allow-${command.replaceAll('_', '-')}`

export function capabilities() {
  const all = appCommands()
  const known = new Set(all)
  const bare = [...reachableCommands(BARE_ENTRIES)].filter((c) => !BARE_DENIED.includes(c)).sort()
  for (const c of bare) if (!known.has(c)) throw new Error(`${c} is used by a small window but is not a registered command`)
  const header = (identifier, description, windows, permissions) => ({
    $schema: '../gen/schemas/desktop-schema.json',
    identifier,
    description,
    windows,
    permissions,
  })
  return {
    'main.json': header(
      'main',
      'The main window: every command of the app (generated by scripts/tauri-capabilities.mjs).',
      ['main'],
      ['core:default', { identifier: 'opener:allow-open-url', allow: [{ url: 'https://*' }, { url: 'mailto:*' }] }, ...[...all].sort().map(permissionOf)],
    ),
    'bare.json': header(
      'bare',
      'The quick switch and prompt windows: only the commands their code can reach, and no plugin access (generated by scripts/tauri-capabilities.mjs).',
      ['quickswitch', 'prompt'],
      ['core:default', ...bare.map(permissionOf)],
    ),
  }
}

const render = (json) => JSON.stringify(json, null, 2) + '\n'

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = capabilities()
  let stale = false
  for (const [name, json] of Object.entries(out)) {
    const path = join(root, 'src-tauri/capabilities', name)
    if (process.argv.includes('--check')) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== render(json)) {
        console.error(`${name} is out of date: run node scripts/tauri-capabilities.mjs`)
        stale = true
      }
    } else {
      writeFileSync(path, render(json))
      console.log(`wrote ${path} (${json.permissions.length} permissions)`)
    }
  }
  if (stale) process.exit(1)
}
